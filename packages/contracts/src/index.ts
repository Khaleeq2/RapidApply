export function isExtensionReadyMessage(value: unknown): value is ExtensionReadyMessage {
  if (!isRecord(value)) return false;

  return (
    value.source === EXTENSION_BRIDGE_SOURCE &&
    value.type === "EXTENSION_READY" &&
    typeof value.version === "string" &&
    (value.activeRunId === undefined || typeof value.activeRunId === "string") &&
    (value.executionState === undefined || isRunState(value.executionState))
  );
}

export function isBrowserExecutorEventCapability(
  value: unknown,
): value is BrowserExecutorEventCapability {
  if (!isRecord(value)) return false;

  return (
    typeof value.runId === "string" &&
    typeof value.token === "string" &&
    value.token.length >= 32 &&
    typeof value.expiresAt === "string"
  );
}

export function isBrowserExecutionPlan(value: unknown): value is BrowserExecutionPlan {
  if (!isRecord(value) || !isRecord(value.preferences)) return false;

  return (
    typeof value.runId === "string" &&
    value.adapterId === "linkedin" &&
    typeof value.targetRole === "string" &&
    typeof value.targetLocation === "string" &&
    typeof value.targetApplications === "number" &&
    Number.isInteger(value.targetApplications) &&
    value.targetApplications > 0 &&
    typeof value.poolTarget === "number" &&
    Number.isInteger(value.poolTarget) &&
    value.poolTarget >= value.targetApplications &&
    (value.autonomyPolicy === undefined || isAutonomyPolicy(value.autonomyPolicy)) &&
    (value.submissionMode === undefined ||
      value.submissionMode === "review_only" ||
      value.submissionMode === "autonomous_submit" ||
      value.submissionMode === "test_submit") &&
    ["entry", "mid", "senior", "lead"].includes(String(value.preferences.experience)) &&
    ["remote", "hybrid", "onsite", "any"].includes(String(value.preferences.workStyle)) &&
    typeof value.preferences.onlyEasyApply === "boolean" &&
    Array.isArray(value.preferences.excludedTerms) &&
    value.preferences.excludedTerms.every((term) => typeof term === "string")
  );
}

function isAutonomyPolicy(value: unknown): value is AutonomyPolicy {
  if (!isRecord(value) || !isRecord(value.maxThroughput)) return false;
  const throughput = value.maxThroughput;
  return (
    (value.mode === "autonomous" || value.mode === "strict_control") &&
    ["ai_draft", "profile_only", "skip_job"].includes(String(value.freeTextStrategy)) &&
    ["defer_to_finish_later", "skip_job", "pause_campaign"].includes(String(value.unknownFieldStrategy)) &&
    typeof value.aiConfidenceThreshold === "number" &&
    value.aiConfidenceThreshold >= 0 &&
    value.aiConfidenceThreshold <= 1 &&
    Number.isInteger(throughput.dailyCap) &&
    typeof throughput.dailyCap === "number" &&
    throughput.dailyCap > 0 &&
    Number.isInteger(throughput.hourlyCap) &&
    typeof throughput.hourlyCap === "number" &&
    throughput.hourlyCap > 0
  );
}

export function isExecutorResumeDocument(value: unknown): value is ExecutorResumeDocument {
  if (!isRecord(value)) return false;

  return (
    typeof value.id === "string" &&
    typeof value.fileName === "string" &&
    /^[A-Za-z0-9]+(?:_[A-Za-z0-9]+)*_Resume_v[1-9][0-9]*\.pdf$/.test(value.fileName) &&
    typeof value.targetRole === "string" &&
    value.targetRole.length > 0 &&
    value.mimeType === "application/pdf" &&
    typeof value.byteSize === "number" &&
    Number.isInteger(value.byteSize) &&
    value.byteSize > 0 &&
    value.byteSize <= 2_000_000 &&
    typeof value.contentHash === "string" &&
    /^[a-f0-9]{64}$/.test(value.contentHash) &&
    typeof value.version === "number" &&
    Number.isInteger(value.version) &&
    value.version > 0 &&
    typeof value.isDefault === "boolean" &&
    typeof value.updatedAt === "string" &&
    typeof value.bytesBase64 === "string" &&
    value.bytesBase64.length > 0
  );
}

