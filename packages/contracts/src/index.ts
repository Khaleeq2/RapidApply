export function isBrowserRunSummary(value: unknown): value is BrowserRunSummary {
  if (!isRecord(value)) return false;

  return (
    typeof value.id === "string" &&
    typeof value.campaignId === "string" &&
    isRunState(value.state) &&
    typeof value.targetRole === "string" &&
    typeof value.targetLocation === "string" &&
    Array.isArray(value.boardIds) &&
    value.boardIds.every((boardId) => typeof boardId === "string") &&
    typeof value.targetApplications === "number" &&
    typeof value.appliedCount === "number" &&
    typeof value.skippedCount === "number" &&
    (typeof value.executorTabId === "number" || value.executorTabId === null) &&
    (typeof value.startedAt === "string" || value.startedAt === null) &&
    (typeof value.completedAt === "string" || value.completedAt === null) &&
    typeof value.createdAt === "string" &&
    typeof value.updatedAt === "string"
  );
}

export function isRunState(value: unknown): value is RunState {
  return typeof value === "string" && (RUN_STATES as readonly string[]).includes(value);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}
